import type { ChallengeStore } from "@/lib/daily/challenge-store";
import { dateForChallengeNumber, type DateKey } from "@/lib/daily/calendar";
import {
  analyzeBoard,
  DEFAULT_RECENCY,
  generateQuartetsSafe,
  groupKey,
  QUARTETS_VERSION,
  type QuartetsData,
} from "./generator";
import { decryptBoard, quartetsSeed, type EncryptedBoard } from "./secret";
import type { DayLevel, QuartetBoard } from "./types";

/** Weekly difficulty curve (UTC): Mon/Tue easy, Wed–Fri medium, Sat/Sun hard. */
export function dayLevel(date: DateKey): DayLevel {
  const weekday = new Date(`${date}T00:00:00Z`).getUTCDay();
  if (weekday === 1 || weekday === 2) return "easy";
  if (weekday === 0 || weekday === 6) return "hard";
  return "medium";
}

/** A frozen daily board, as stored in data/daily-challenges.json (`connections` section). */
export interface FrozenQuartets {
  /** AES-256-GCM encrypted QuartetBoard (solution + layout), bound to the challenge number. */
  board: EncryptedBoard;
  level: DayLevel;
  generatorVersion: string;
  /** 0 = normal generation path; >0 = generated by a fallback step. */
  fallbackStep: number;
  dataset: { count: number; hash: string };
  /** Random, answer-independent progress key for the client. */
  salt: string;
  frozenAt: string;
}

export interface DailyQuartets {
  number: number;
  date: DateKey;
  level: DayLevel;
  /** null when the secret key is missing/invalid: the game is unavailable. */
  board: QuartetBoard | null;
  progressKey: string;
  source: "frozen" | "generated" | "unavailable";
}

/** History of the `days` boards before `number` (most recent first), for recency rules. */
export function boardHistory(
  number: number,
  lookup: (n: number) => QuartetBoard | null,
  days: number,
): { recentCategories: string[][]; recentGroups: Set<string> } {
  const recentCategories: string[][] = [];
  const recentGroups = new Set<string>();
  for (let n = number - 1, i = 0; n >= 1 && i < days; n--, i++) {
    const board = lookup(n);
    if (i < DEFAULT_RECENCY.softDays) recentCategories.push(board ? board.groups.map((g) => g.categoryId) : []);
    board?.groups.forEach((g) => recentGroups.add(groupKey(g.pokemonIds)));
  }
  return { recentCategories, recentGroups };
}

/** Generates the board for a day given its history. Never throws. */
export function generateDailyQuartets(
  number: number,
  deps: { data: QuartetsData; key: Buffer; lookup: (n: number) => QuartetBoard | null },
) {
  const level = dayLevel(dateForChallengeNumber(number));
  const history = boardHistory(number, deps.lookup, DEFAULT_RECENCY.groupDays);
  return {
    level,
    ...generateQuartetsSafe({ seed: quartetsSeed(deps.key, number, QUARTETS_VERSION), data: deps.data, level, ...history }),
  };
}

/**
 * Resolves the Cuartetos board for a challenge number. Never throws.
 * Frozen (encrypted) boards win; unfrozen days are generated with the secret
 * seed; without a key the game is unavailable (never a guessable fallback).
 */
export function resolveDailyQuartets(
  number: number,
  deps: { data: QuartetsData; store: ChallengeStore; key: Buffer | null; onWarning?: (message: string) => void },
): DailyQuartets {
  const date = dateForChallengeNumber(number);
  const level = dayLevel(date);
  const warn = deps.onWarning ?? (() => {});
  const stored = deps.store.get<FrozenQuartets>("connections", number);

  if (!deps.key) {
    warn("GUESS_SECRET_KEY is missing or invalid; Cuartetos is unavailable.");
    return { number, date, level, board: null, progressKey: stored?.payload.salt ?? "unavailable", source: "unavailable" };
  }

  const decrypt = (n: number) => {
    const entry = deps.store.get<FrozenQuartets>("connections", n);
    return entry ? decryptBoard(entry.payload.board, n, deps.key!) : null;
  };

  if (stored) {
    const board = decrypt(number);
    if (board && analyzeBoard(board, deps.data).problems.length === 0) {
      return { number, date: stored.date, level: stored.payload.level, board, progressKey: stored.payload.salt, source: "frozen" };
    }
    // A frozen day must never silently change: report unavailable instead.
    warn(`Frozen Cuartetos #${number} could not be decrypted or is invalid; game unavailable.`);
    return { number, date, level, board: null, progressKey: stored.payload.salt, source: "unavailable" };
  }

  warn(`Cuartetos #${number} is not frozen; generating on the fly. Run \`npm run quartets:freeze\`.`);
  const generated = generateDailyQuartets(number, { data: deps.data, key: deps.key, lookup: decrypt });
  return { number, date, level, board: generated.board, progressKey: `generated:v${QUARTETS_VERSION}`, source: "generated" };
}
