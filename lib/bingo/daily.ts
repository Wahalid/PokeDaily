import type { SealedBox } from "@/lib/crypto/sealed";
import type { ChallengeStore } from "@/lib/daily/challenge-store";
import { dateForChallengeNumber, type DateKey } from "@/lib/daily/calendar";
import type { QuartetsData } from "@/lib/quartets/generator";
import { analyzeBingo, BINGO_VERSION, DEFAULT_BINGO_RECENCY, generateBingoSafe } from "./generator";
import { bingoSeed, openBingo } from "./secret";
import type { BingoChallenge } from "./types";

/** A frozen daily PokéBingo, as stored in data/daily-challenges.json (`bingo` section). */
export interface FrozenBingo {
  /** AES-256-GCM sealed BingoChallenge (cells + ordered deck), bound to the challenge number. */
  challenge: SealedBox;
  generatorVersion: string;
  /** 0 = normal generation path; >0 = generated by a fallback step. */
  fallbackStep: number;
  dataset: { count: number; hash: string };
  /** Random, answer-independent progress key for the client. */
  salt: string;
  frozenAt: string;
}

export interface DailyBingo {
  number: number;
  date: DateKey;
  /** null when the secret key is missing/invalid: the game is unavailable. */
  challenge: BingoChallenge | null;
  progressKey: string;
  source: "frozen" | "generated" | "unavailable";
}

/** Generates the challenge for a day given the previous days. Never throws. */
export function generateDailyBingo(
  number: number,
  deps: { data: QuartetsData; key: Buffer; lookup: (n: number) => BingoChallenge | null },
) {
  const recentCategories: string[][] = [];
  const recentPokemon: number[][] = [];
  const days = Math.max(DEFAULT_BINGO_RECENCY.softDays, DEFAULT_BINGO_RECENCY.pokemonDays);
  for (let n = number - 1, i = 0; n >= 1 && i < days; n--, i++) {
    const previous = deps.lookup(n);
    recentCategories.push(previous?.cells ?? []);
    recentPokemon.push(previous?.deck ?? []);
  }
  return generateBingoSafe({
    seed: bingoSeed(deps.key, number, BINGO_VERSION),
    data: deps.data,
    recentCategories,
    recentPokemon,
  });
}

/**
 * Resolves the PokéBingo for a challenge number. Never throws.
 * Frozen (sealed) challenges win; unfrozen days are generated with the secret
 * seed; without a key the game is unavailable (never a guessable fallback).
 */
export function resolveDailyBingo(
  number: number,
  deps: { data: QuartetsData; store: ChallengeStore; key: Buffer | null; onWarning?: (message: string) => void },
): DailyBingo {
  const date = dateForChallengeNumber(number);
  const warn = deps.onWarning ?? (() => {});
  const stored = deps.store.get<FrozenBingo>("bingo", number);

  if (!deps.key) {
    warn("GUESS_SECRET_KEY is missing or invalid; PokéBingo is unavailable.");
    return { number, date, challenge: null, progressKey: stored?.payload.salt ?? "unavailable", source: "unavailable" };
  }
  const open = (n: number) => {
    const entry = deps.store.get<FrozenBingo>("bingo", n);
    return entry ? openBingo(entry.payload.challenge, n, deps.key!) : null;
  };

  if (stored) {
    const challenge = open(number);
    if (challenge && analyzeBingo(challenge, deps.data).problems.length === 0) {
      return { number, date: stored.date, challenge, progressKey: stored.payload.salt, source: "frozen" };
    }
    warn(`Frozen PokéBingo #${number} could not be decrypted or is invalid; game unavailable.`);
    return { number, date, challenge: null, progressKey: stored.payload.salt, source: "unavailable" };
  }

  warn(`PokéBingo #${number} is not frozen; generating on the fly. Run \`npm run bingo:freeze\`.`);
  const generated = generateDailyBingo(number, { data: deps.data, key: deps.key, lookup: open });
  return { number, date, challenge: generated.challenge, progressKey: `generated:v${BINGO_VERSION}`, source: "generated" };
}
